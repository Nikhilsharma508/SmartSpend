import { useMemo, useState } from "react"
import { motion } from "motion/react"
import { Download, Info } from "lucide-react"
import { toast } from "sonner"
import { Link } from "react-router-dom"
import { RangeSlider } from "@/components/range-slider"
import { SwitchVeil } from "@/components/switch-veil"
import { KpiCard } from "@/components/kpi-card"
import { ProfitCurveChart } from "@/components/charts/profit-curve-chart"
import { LoadError } from "@/components/load-error"
import { Term, ToolChip } from "@/components/term"
import { Badge } from "@/components/ui/badge"
import { Button } from "@/components/ui/button"
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card"
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table"
import { useOverview } from "@/hooks/use-overview"
import { usePreserveScrollDuringSwap } from "@/hooks/use-preserve-scroll"
import { buildCsv, downloadCsv } from "@/lib/csv"
import { interpPoint, intFmt, rateFmt, usd } from "@/lib/format"
import { cn } from "@/lib/utils"

/** One-click spends that set the depth (the only honest lever: everything —
 * contacts, targeting depth, budget — is the same knob read in a different
 * unit). */
const BUDGET_PRESETS = [100, 250, 500, 1_000, 2_000]

export default function PlannerPage() {
  const { data: fx, isPending, isError, error, isPlaceholderData, switchingLabel } =
    useOverview()
  // a model swap must not move the reader
  usePreserveScrollDuringSwap(isPlaceholderData)
  const [depth, setDepth] = useState<number | null>(null)

  const curve = fx?.profit_curve
  const chosen = useMemo(
    () => (curve ? interpPoint(curve.points, depth ?? curve.recommended_depth ?? 0.3) : null),
    [curve, depth],
  )

  const costPerContact = fx?.assumptions.cost_per_contact_usd
  const budget = chosen && costPerContact ? chosen.point.n_targeted * costPerContact : 0

  const csvPlan = useMemo(() => {
    if (!fx || !chosen) return null
    const rows = fx.segment_profile.segments.map((s) => ({
      segment_id: s.segment_id,
      targeting_rules: s.rules.join(" AND "),
      policy_arm: s.policy_arm,
      customers_in_holdout_eval: s.n_eval,
      share_of_list: +s.share.toFixed(4),
      planned_contacts: Math.round(s.share * chosen.point.n_targeted),
      expected_incremental_visits: +(s.uplift_visit * s.share * chosen.point.n_targeted).toFixed(2),
      visit_uplift_ci_low: +s.uplift_visit_ci_low.toFixed(4),
      visit_uplift_ci_high: +s.uplift_visit_ci_high.toFixed(4),
    }))
    const headerNote = [
      {
        segment_id: `plan generated by SmartSpend apps/web — model ${fx.context.model_name ?? "champion"} at depth ${(chosen.point.depth * 100).toFixed(1)}% of the ${intFmt(fx.context.n_test)}-customer holdout; money columns are US dollars at the Day-1 assumptions.`,
        targeting_rules: "",
        policy_arm: "",
        customers_in_holdout_eval: "",
        share_of_list: "",
        planned_contacts: "",
        expected_incremental_visits: "",
        visit_uplift_ci_low: "",
        visit_uplift_ci_high: "",
      },
    ]
    return buildCsv([...headerNote, ...rows])
  }, [fx, chosen])

  if (isPending) {
    return (
      <div className="grid gap-4">
        {[0, 1].map((i) => (
          <div
            key={i}
            className="h-40 animate-pulse rounded-xl border border-border/60 bg-muted/40"
          />
        ))}
      </div>
    )
  }

  if (isError || !fx || !curve || !chosen) {
    return <LoadError error={error} />
  }

  const activeDepth = chosen.point.depth
  // the tool's priced grid starts at 2%, not 0% — map by depth, never by
  // assuming depth × (len−1) is an index
  const recDepth = curve.recommended_depth ?? 0
  const recPoint = curve.points.reduce(
    (best, p) => (Math.abs(p.depth - recDepth) < Math.abs(best.depth - recDepth) ? p : best),
    curve.points[0]!,
  )
  const recProfit = curve.recommended_profit_usd ?? 0
  const contactCost = fx.assumptions.cost_per_contact_usd
  // the depth slider covers the tool's priced half of the list
  const maxUsefulBudget = 0.5 * contactCost * fx.context.n_test

  const budgetToDepth = (usd: number) =>
    setDepth(Math.max(0, Math.min(0.5, usd / (contactCost * fx.context.n_test))))

  // a preset above the cap spends the same as the cap — highlight only the
  // first preset that lands on the current spend
  const presetSpend = (v: number) => Math.min(v, Math.round(maxUsefulBudget))
  const activePreset = BUDGET_PRESETS.find((v) => presetSpend(v) === Math.round(budget))

  return (
    <div className="relative space-y-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-xl font-semibold tracking-tight">Planner</h1>
          <p className="mt-1 max-w-3xl text-sm text-muted-foreground">
            One lever, three units: what you spend decides the <Term k="depth">depth</Term>{" "}
            of the list — from the customers the model ranks most persuadable onward.
            {curve.note}
          </p>
        </div>
        <div className="flex items-center gap-2">
          <Badge variant="outline" className="text-[11px] font-medium">
            {fx.context.model_label ?? "Champion"}
          </Badge>
          <Badge
            variant="outline"
            className={cn(
              "text-[10px]",
              fx.context.tier === "champion"
                ? "border-dashed"
                : "border-amber-400/40 bg-amber-400/10 text-amber-500 dark:text-amber-300",
            )}
          >
            {fx.context.tier}
          </Badge>
        </div>
      </div>

      {/* KPI row */}
      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <KpiCard
          label="Recommended depth"
          value={(curve.recommended_depth ?? 0) * 100}
          format={(n) => `${n.toFixed(1)}%`}
          sub={`targets ≈ ${usd(recProfit)}`}
          accentClass="bg-primary"
          hint="The whole contact list was priced at every possible cut; this is where average profit peaks."
        />
        <KpiCard
          label="Profit at recommended"
          value={recProfit}
          format={(n) => usd(n)}
          sub={`95% band ${usd(recPoint?.profit_ci_low_usd ?? 0)} – ${usd(recPoint?.profit_ci_high_usd ?? 0)}`}
          accentClass="bg-[var(--color-profit)]"
          hint="Extra conversions × margin × value per conversion, minus send costs. The band is the 95% CI — an estimate, not a promise."
        />
        <KpiCard
          label="Break-even depth"
          value={(curve.break_even_depth ?? 0) * 100}
          format={(n) => `${n.toFixed(1)}%`}
          sub="targeting deeper than this loses money"
          accentClass="bg-[var(--color-loss)]"
          hint="The first priced depth where expected profit crosses $0 — send costs start outweighing the extra conversions."
        />
        <KpiCard
          label="Profit at your depth"
          value={chosen.point.profit_usd}
          format={(n) => usd(n)}
          sub={`${intFmt(chosen.point.n_targeted)} contacts · ${chosen.point.incremental_conversions.toFixed(1)} extra conversions`}
          accentClass="bg-amber-400"
          hint={
            chosen.exact
              ? "Your depth is one of the tool's priced points."
              : "Your depth sits between two priced points — the numbers are interpolated from the two neighbours."
          }
        />
      </div>

      {fx.context.tier === "research" && (
        <p className="rounded-xl border border-amber-400/40 bg-amber-400/10 px-4 py-3 text-xs leading-relaxed text-amber-600 dark:text-amber-300">
          You are planning with a <Term k="researchMode">research-only</Term> model — over
          the 10-seed benchmark its ranking was statistically at random, so a curve this
          clean is single-split luck. Fine for exploration; for a live campaign, switch
          back to champion or the DR challenger right in the header pill.
        </p>
      )}

      {/* Hero chart */}
      <Card className="overflow-hidden border-border/60 bg-card/70 backdrop-blur-sm">
        <CardHeader className="pb-0">
          <div className="flex items-start justify-between gap-4">
            <div>
              <CardTitle className="text-base">Profit curve over <Term k="depth">depth</Term></CardTitle>
              <CardDescription className="flex flex-wrap items-center gap-x-1.5 gap-y-1">
                As you target deeper (most persuadable first), profit climbs to a peak and
                then slides — drag the white marker to pick your depth ·{" "}
                <ToolChip name="optimize_budget" />
                <span className="font-mono text-[10.5px]">seed-42 split</span>
              </CardDescription>
            </div>
            <Badge variant="outline" className="gap-1 border-dashed text-[11px]">
              <Info className="size-3" />
              mean with 95% band
            </Badge>
          </div>
        </CardHeader>
        <CardContent className="pt-2">
          <ProfitCurveChart
            curve={curve}
            chosenDepth={activeDepth}
            onChooseDepth={setDepth}
          />
        </CardContent>
      </Card>

      {/* Budget + scenarios — full-width cards so nothing leaves dead space */}
      <div className="grid gap-4">
        <Card className="flex h-full flex-col border-border/60 bg-card/70 backdrop-blur-sm">
          <CardHeader>
            <CardTitle className="text-base">Your budget</CardTitle>
            <CardDescription>
              contacts cost {usd(contactCost, 2)} each — you can steer by money or by
              targeting depth, they are the same lever
            </CardDescription>
          </CardHeader>
          <CardContent className="flex flex-1 flex-col gap-5">
            <div className="grid gap-6 sm:grid-cols-2">
              <RangeSlider
                value={Math.round(budget)}
                min={25}
                max={Math.max(100, Math.round(maxUsefulBudget))}
                step={1}
                onValueChange={budgetToDepth}
                label="total spend"
                valueText={usd(budget)}
                ticks={[usd(25), usd(maxUsefulBudget / 2), usd(maxUsefulBudget)]}
              />
              <RangeSlider
                value={activeDepth * 100}
                min={0}
                max={50}
                step={0.5}
                onValueChange={(v) => setDepth(v / 100)}
                label="targeting depth"
                valueText={`${(activeDepth * 100).toFixed(1)}%`}
                ticks={["0%", "25%", "50%"]}
              />
            </div>

            {/* quick spends */}
            <div className="flex flex-wrap items-center gap-1.5">
              <span className="mr-1 text-[10px] uppercase tracking-wider text-muted-foreground">
                quick picks
              </span>
              {BUDGET_PRESETS.map((v) => (
                <button
                  key={v}
                  onClick={() => budgetToDepth(v)}
                  className={cn(
                    "rounded-full border px-2.5 py-0.5 text-[11px] font-medium transition-colors",
                    activePreset === v
                      ? "border-primary/60 bg-primary/10 text-primary"
                      : "border-border/70 bg-muted/30 text-muted-foreground hover:text-foreground",
                  )}
                >
                  ${v.toLocaleString("en-US")}
                </button>
              ))}
            </div>

            {/* derived, all from the tool's grid */}
            <div className="grid grid-cols-2 gap-3 rounded-xl border border-border/50 bg-muted/20 p-3 sm:grid-cols-4">
              <MiniStat label="customers contacted" value={intFmt(chosen.point.n_targeted)} />
              <MiniStat
                label="extra conversions"
                value={chosen.point.incremental_conversions.toFixed(1)}
              />
              <MiniStat label="expected profit" value={usd(chosen.point.profit_usd)} />
              <MiniStat
                label="95% band"
                value={`${usd(chosen.point.profit_ci_low_usd)} – ${usd(chosen.point.profit_ci_high_usd)}`}
              />
            </div>

            {/* the honest limit + the re-pricing path */}
            <p className="text-xs leading-relaxed text-muted-foreground">
              The curve stops at half the <Term k="holdout">holdout</Term> ({intFmt(fx.context.n_test)}{" "}
              customers) — money beyond ≈{usd(maxUsefulBudget, 0)} has nobody left to
              contact, so it cannot buy more depth.
            </p>
            <div className="mt-auto">
              <div className="flex flex-wrap gap-1.5 text-[10px]">
                <span className="rounded-md bg-muted/70 px-1.5 py-0.5 font-mono">
                  cost {usd(contactCost, 2)}/contact
                </span>
                <span className="rounded-md bg-muted/70 px-1.5 py-0.5 font-mono">
                  margin {(fx.assumptions.margin_rate * 100).toFixed(0)}%
                </span>
                <span className="rounded-md bg-muted/70 px-1.5 py-0.5 font-mono">
                  value {usd(fx.assumptions.value_per_conversion_usd)}/conversion
                </span>
              </div>
              <p className="mt-2 text-[11px] leading-relaxed text-muted-foreground">
                These are the global business assumptions — the curve above is priced at
                them. Want different numbers?{" "}
                <Link
                  to="/copilot"
                  className="font-medium text-foreground underline decoration-primary/40 underline-offset-2"
                >
                  Ask the copilot “what if contact cost doubles?”
                </Link>{" "}
                and it re-prices the plan.
              </p>
            </div>
          </CardContent>
        </Card>

        <Card className="border-border/60 bg-card/70 backdrop-blur-sm">
          <CardHeader>
            <CardTitle className="text-base">Scenario comparison</CardTitle>
            <CardDescription>{fx.scenarios.note}</CardDescription>
          </CardHeader>
          <CardContent>
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Strategy</TableHead>
                  <TableHead className="text-right">Contacts targeted</TableHead>
                  <TableHead className="text-right">Extra conversions</TableHead>
                  <TableHead className="text-right">Profit (USD)</TableHead>
                  <TableHead className="text-right">95% band</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {fx.scenarios.scenarios.map((s) => {
                  const ranked = s.strategy.toLowerCase().endsWith("ranking")
                  return (
                    <TableRow
                      key={s.strategy}
                      className={cn(
                        ranked && "bg-primary/5",
                        !s.feasible && "opacity-70",
                      )}
                    >
                      <TableCell className="whitespace-normal font-medium">
                        <span className="flex items-center gap-2">
                          {s.strategy}
                          {ranked && fx.scenarios.champion_wins && (
                            <Badge className="bg-[var(--color-profit)]/15 text-[10px] text-[var(--color-profit)]">
                              wins
                            </Badge>
                          )}
                        </span>
                        {ranked && (
                          <span className="text-[11px] text-muted-foreground">
                            the model's top picks at {rateFmt(fx.scenarios.depth, 0)} depth
                          </span>
                        )}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {intFmt(s.n_targeted)}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {s.incremental_conversions.toFixed(2)}
                      </TableCell>
                      <TableCell
                        className={cn(
                          "text-right font-semibold tabular-nums",
                          s.profit_usd >= 0
                            ? "text-[var(--color-profit)]"
                            : "text-[var(--color-loss)]",
                        )}
                      >
                        {usd(s.profit_usd)}
                      </TableCell>
                      <TableCell className="text-right tabular-nums text-muted-foreground">
                        {usd(s.profit_ci_low_usd)} – {usd(s.profit_ci_high_usd)}
                      </TableCell>
                    </TableRow>
                  )
                })}
              </TableBody>
            </Table>
            <p className="mt-3 text-[11px] leading-relaxed text-muted-foreground">
              “Extra conversions” counts versus contacting the same budget uniformly at
              random — the honest baseline every strategy is measured against.
            </p>
          </CardContent>
        </Card>
      </div>

      {/* CSV export */}
      <Card className="border-border/60 bg-card/70 backdrop-blur-sm">
        <CardContent className="flex flex-wrap items-center justify-between gap-4 py-5">
          <div className="space-y-1">
            <div className="flex items-center gap-2">
              <span className="text-sm font-medium">Targeting plan export</span>
              <Badge variant="outline" className="text-[10px]">
                CSV
              </Badge>
            </div>
            <p className="text-xs text-muted-foreground">
              {fx.segment_profile.segments.length} rule-based segments × your chosen depth
              ({rateFmt(activeDepth, 0)}) — rules, planned contacts and per-segment
              estimated extra visits with confidence bands.
            </p>
          </div>
          <motion.div whileHover={{ scale: 1.03 }} whileTap={{ scale: 0.97 }}>
            <Button
              className="gap-2"
              onClick={() => {
                if (!csvPlan) return
                downloadCsv(
                  `smartspend_target_plan_d${(activeDepth * 100).toFixed(0)}.csv`,
                  csvPlan,
                )
                toast.success("Targeting plan downloaded", {
                  description: `${fx.segment_profile.segments.length} segment rows at depth ${rateFmt(activeDepth, 0)}.`,
                })
              }}
            >
              <Download className="size-4" />
              Download CSV
            </Button>
          </motion.div>
        </CardContent>
      </Card>

      {/* the outgoing model stays mounted while the next one loads — no
          skeleton collapse, no scroll jump; the veil hides the old numbers */}
      <SwitchVeil show={isPlaceholderData} label={switchingLabel} />
    </div>
  )
}

function MiniStat({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <p className="text-[10px] uppercase tracking-wider text-muted-foreground">{label}</p>
      <p className="mt-0.5 text-sm font-semibold tabular-nums">{value}</p>
    </div>
  )
}
