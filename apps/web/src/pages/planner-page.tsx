import { useMemo, useState } from "react"
import { motion } from "motion/react"
import { Download, Info } from "lucide-react"
import { toast } from "sonner"
import LiquidSlider from "@/components/kokonutui/liquid-slider"
import { KpiCard } from "@/components/kpi-card"
import { ProfitCurveChart } from "@/components/charts/profit-curve-chart"
import { Badge } from "@/components/ui/badge"
import { Button } from "@/components/ui/button"
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card"
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table"
import { useFixtures } from "@/hooks/use-fixtures"
import { buildCsv, downloadCsv } from "@/lib/csv"
import { interpPoint, intFmt, rateFmt, usd } from "@/lib/format"
import { cn } from "@/lib/utils"

export default function PlannerPage() {
  const { data: fx, isPending, isError, error } = useFixtures()
  const [depth, setDepth] = useState<number | null>(null)

  const curve = fx?.profit_curve
  const chosen = useMemo(
    () => (curve ? interpPoint(curve.points, depth ?? curve.recommended_depth ?? 0.3) : null),
    [curve, depth],
  )

  const budget = chosen
    ? chosen.point.n_targeted * (fx!.assumptions.cost_per_contact_usd)
    : 0

  const csvPlan = useMemo(() => {
    if (!fx || !chosen) return null
    const rows = fx.segment_profile.segments.map((s) => ({
      segment_id: s.segment_id,
      targeting_rules: s.rules.join(" AND "),
      policy_arm: s.policy_arm,
      customers_in_holdout_eval: s.n_eval,
      share_of_list: +s.share.toFixed(4),
      planned_contacts: Math.round(s.share * chosen.point.n_targeted),
      expected_incremental_visits: +(s.uplift_visit * s.share * chosen.point.n_targeted).toFixed(2),
      visit_uplift_ci_low: +s.uplift_visit_ci_low.toFixed(4),
      visit_uplift_ci_high: +s.uplift_visit_ci_high.toFixed(4),
    }))
    const headerNote = [
      {
        segment_id: `plan generated by SmartSpend apps/web — depth ${(chosen.point.depth * 100).toFixed(1)}% of the ${intFmt(fx.context.n_test)}-customer holdout; money columns are US dollars at the Day-1 assumptions.`,
        targeting_rules: "",
        policy_arm: "",
        customers_in_holdout_eval: "",
        share_of_list: "",
        planned_contacts: "",
        expected_incremental_visits: "",
        visit_uplift_ci_low: "",
        visit_uplift_ci_high: "",
      },
    ]
    return buildCsv([...headerNote, ...rows])
  }, [fx, chosen])

  if (isPending) {
    return (
      <div className="grid gap-4">
        {[0, 1].map((i) => (
          <div
            key={i}
            className="h-40 animate-pulse rounded-xl border border-border/60 bg-muted/40"
          />
        ))}
      </div>
    )
  }

  if (isError || !fx || !curve || !chosen) {
    return (
      <div className="rounded-xl border border-destructive/40 bg-destructive/10 p-4 text-sm">
        {(error as Error | null)?.message ?? "Fixtures failed to load."}
      </div>
    )
  }

  const a = fx.assumptions
  const recProfit = curve.recommended_profit_usd ?? 0
  const activeDepth = chosen.point.depth
  const contactCost = a.cost_per_contact_usd

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-xl font-semibold tracking-tight">Planner</h1>
        <p className="mt-1 max-w-3xl text-sm text-muted-foreground">{curve.note}</p>
      </div>

      {/* KPI row */}
      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <KpiCard
          label="Recommended depth"
          value={(curve.recommended_depth ?? 0) * 100}
          format={(n) => `${n.toFixed(1)}%`}
          sub={`effect-homogeneous budget split · ${usd(recProfit)}`}
          accentClass="bg-primary"
          hint="optimize_budget's argmax of mean profit over depth, seed-42 holdout."
        />
        <KpiCard
          label="Profit at recommended"
          value={recProfit}
          format={(n) => usd(n)}
          sub={`95% CI ${usd(curve.points[Math.round((curve.recommended_depth ?? 0.3) * 24)]?.profit_ci_low_usd ?? 0)} – ${usd(curve.points[Math.round((curve.recommended_depth ?? 0.3) * 24)]?.profit_ci_high_usd ?? 0)}`}
          accentClass="bg-[var(--color-profit)]"
          hint="Mean + margin·value·lift − cost·n over the top-k segment; bootstrap CI."
        />
        <KpiCard
          label="Break-even depth"
          value={(curve.break_even_depth ?? 0) * 100}
          format={(n) => `${n.toFixed(1)}%`}
          sub="deeper targeting loses money"
          accentClass="bg-[var(--color-loss)]"
          hint="First grid depth where mean profit crosses $0."
        />
        <KpiCard
          label="Profit at your depth"
          value={chosen.point.profit_usd}
          format={(n) => usd(n)}
          sub={`${intFmt(chosen.point.n_targeted)} contacts · Δconv ${chosen.point.incremental_conversions.toFixed(1)}`}
          accentClass="bg-amber-400"
          hint={
            chosen.exact
              ? "Read from the tool's depth grid."
              : "Linear interpolation between the tool's neighbouring grid points."
          }
        />
      </div>

      {/* Hero chart */}
      <Card className="overflow-hidden border-border/60 bg-card/70 backdrop-blur-sm">
        <CardHeader className="pb-0">
          <div className="flex items-start justify-between gap-4">
            <div>
              <CardTitle className="text-base">Profit curve over targeting depth</CardTitle>
              <CardDescription>
                optimize_budget · champion scores on the seed-42 test split ·
                drag the white marker to choose a depth
              </CardDescription>
            </div>
            <Badge variant="outline" className="gap-1 border-dashed text-[11px]">
              <Info className="size-3" />
              mean ± 95% bootstrap CI
            </Badge>
          </div>
        </CardHeader>
        <CardContent className="pt-2">
          <ProfitCurveChart
            curve={curve}
            chosenDepth={activeDepth}
            onChooseDepth={setDepth}
          />
        </CardContent>
      </Card>

      {/* Budget + scenarios */}
      <div className="grid gap-4 lg:grid-cols-5">
        <Card className="border-border/60 bg-card/70 backdrop-blur-sm lg:col-span-2">
          <CardHeader>
            <CardTitle className="text-base">Budget</CardTitle>
            <CardDescription>
              contacts cost {usd(contactCost, 2)} each, so your $ budget picks the depth
            </CardDescription>
          </CardHeader>
          <CardContent>
            <LiquidSlider
              value={Math.round(budget)}
              min={25}
              max={2000}
              step={1}
              label="total spend, USD"
              formatValue={(v) => `$${Math.round(v).toLocaleString("en-US")}`}
              onValueChange={(v) => {
                const d = v / (contactCost * fx.context.n_test)
                setDepth(Math.max(0, Math.min(0.5, d)))
              }}
              className="w-full"
            />
            <p className="mt-3 text-xs leading-relaxed text-muted-foreground">
              ≈ {intFmt(chosen.point.n_targeted)} contacts →{" "}
              <span className="font-medium text-foreground">{rateFmt(activeDepth, 1)}</span> depth.
              The grid tops out at 50% of the contactable list (10k holdout
              round: {intFmt(fx.context.n_test)} customers); spend beyond ≈
              $425 buys every contact, so it cannot raise depth further.
            </p>
          </CardContent>
        </Card>

        <Card className="border-border/60 bg-card/70 backdrop-blur-sm lg:col-span-3">
          <CardHeader>
            <CardTitle className="text-base">Scenario comparison</CardTitle>
            <CardDescription>{fx.scenarios.note}</CardDescription>
          </CardHeader>
          <CardContent>
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Strategy</TableHead>
                  <TableHead className="text-right">Targeted</TableHead>
                  <TableHead className="text-right">Δ conversions</TableHead>
                  <TableHead className="text-right">Profit (USD)</TableHead>
                  <TableHead className="text-right">95% CI</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {fx.scenarios.scenarios.map((s) => {
                  const champ = s.strategy.toLowerCase().includes("champion")
                  return (
                    <TableRow
                      key={s.strategy}
                      className={cn(
                        champ && "bg-primary/5",
                        !s.feasible && "opacity-70",
                      )}
                    >
                      <TableCell className="font-medium">
                        <span className="flex items-center gap-2">
                          {s.strategy}
                          {champ && fx.scenarios.champion_wins && (
                            <Badge className="bg-[var(--color-profit)]/15 text-[10px] text-[var(--color-profit)]">
                              wins
                            </Badge>
                          )}
                        </span>
                        {champ && (
                          <span className="text-[11px] text-muted-foreground">
                            at {rateFmt(fx.scenarios.depth, 0)} depth
                          </span>
                        )}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {intFmt(s.n_targeted)}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {s.incremental_conversions.toFixed(2)}
                      </TableCell>
                      <TableCell
                        className={cn(
                          "text-right font-semibold tabular-nums",
                          s.profit_usd >= 0
                            ? "text-[var(--color-profit)]"
                            : "text-[var(--color-loss)]",
                        )}
                      >
                        {usd(s.profit_usd)}
                      </TableCell>
                      <TableCell className="text-right tabular-nums text-muted-foreground">
                        {usd(s.profit_ci_low_usd)} – {usd(s.profit_ci_high_usd)}
                      </TableCell>
                    </TableRow>
                  )
                })}
              </TableBody>
            </Table>
          </CardContent>
        </Card>
      </div>

      {/* CSV export */}
      <Card className="border-border/60 bg-card/70 backdrop-blur-sm">
        <CardContent className="flex flex-wrap items-center justify-between gap-4 py-5">
          <div className="space-y-1">
            <div className="flex items-center gap-2">
              <span className="text-sm font-medium">Targeting plan export</span>
              <Badge variant="outline" className="text-[10px]">
                CSV
              </Badge>
            </div>
            <p className="text-xs text-muted-foreground">
              {fx.segment_profile.segments.length} rule-based segments × your chosen depth
              ({rateFmt(activeDepth, 0)}) — rules, planned contacts and per-segment
              incremental-visit estimates with CIs. Foreign-keyed to the holdout eval
              set, not customer PII.
            </p>
          </div>
          <motion.div whileHover={{ scale: 1.03 }} whileTap={{ scale: 0.97 }}>
            <Button
              className="gap-2"
              onClick={() => {
                if (!csvPlan) return
                downloadCsv(
                  `smartspend_target_plan_d${(activeDepth * 100).toFixed(0)}.csv`,
                  csvPlan,
                )
                toast.success("Targeting plan downloaded", {
                  description: `${fx.segment_profile.segments.length} segment rows at depth ${rateFmt(activeDepth, 0)}.`,
                })
              }}
            >
              <Download className="size-4" />
              Download CSV
            </Button>
          </motion.div>
        </CardContent>
      </Card>
    </div>
  )
}
